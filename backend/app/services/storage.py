"""
Where uploaded files live.

Routes only talk to the Storage interface (save, delete, url), never to the
filesystem directly. Today the only implementation is LocalStorage, which
writes under backend/uploads/ and is served by the /uploads mount in main.py.

Before deploying to a host with a throwaway filesystem (Render's free tier
deletes files on every redeploy, restart, or spin-down), add an
object-storage class (e.g. Cloudflare R2 via boto3) with the same three
methods and return it from get_storage(). Nothing else needs to change,
because the database stores only keys like "entries/abc123.webp".
"""

import os
import re
import tempfile
from functools import lru_cache
from pathlib import Path
from typing import Annotated, Protocol

from fastapi import Depends

from app.core.config import get_settings

# Keys are generated by the app (see services/photos.py), never taken from a
# user. Checking the shape anyway means a bug can never turn a key into a
# path outside the upload folder (e.g. "../.env").
KEY_PATTERN = re.compile(r"^[A-Za-z0-9_-]+(?:/[A-Za-z0-9_-]+)*\.webp$")


class Storage(Protocol):
    """Anything that can store, remove, and link to a file by key."""

    def save(self, key: str, data: bytes) -> None: ...

    def delete(self, key: str) -> None: ...

    def url(self, key: str) -> str: ...


class LocalStorage:
    """Files on this machine's disk, under `root`, served at `base_url`."""

    def __init__(self, root: Path, base_url: str) -> None:
        self.root = root.resolve()
        self.base_url = base_url.rstrip("/")

    def _path(self, key: str) -> Path:
        if not KEY_PATTERN.match(key):
            raise ValueError(f"Invalid storage key: {key!r}")
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root):
            raise ValueError(f"Storage key escapes the upload folder: {key!r}")
        return path

    def save(self, key: str, data: bytes) -> None:
        """Write atomically: readers never see a half-written file."""
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=path.parent, suffix=".tmp")
        try:
            with os.fdopen(fd, "wb") as f:
                f.write(data)
            os.replace(tmp, path)
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise

    def delete(self, key: str) -> None:
        """Remove the file. Already gone is fine (deleting twice is harmless)."""
        self._path(key).unlink(missing_ok=True)

    def url(self, key: str) -> str:
        self._path(key)  # validate
        return f"{self.base_url}/{key}"


@lru_cache
def get_storage() -> Storage:
    """The storage the app uses. Cached: one instance per process."""
    settings = get_settings()
    return LocalStorage(settings.upload_dir, settings.media_base_url)


# Lets routes ask for storage in their signature, and lets tests swap it out
# with app.dependency_overrides[get_storage].
StorageDep = Annotated[Storage, Depends(get_storage)]
